// Seller-side license tool. Runs on your machine only; nothing here ships in the extension.
//
//   npm run license -- keygen          create the signing key pair (once)
//   npm run license -- issue <orderId> print a license key for a purchase
//   npm run license -- verify <key>    check a key against the public key
//
// The private key lives in .license/private-key.json (git-ignored). Back it up somewhere safe:
// if it's lost, you can't issue keys that existing Burrow versions accept, and if it leaks,
// anyone can make keys.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const KEY_PREFIX = 'BRW1-';
const ALGORITHM = { name: 'ECDSA', namedCurve: 'P-256' };
const SIGN_PARAMS = { name: 'ECDSA', hash: 'SHA-256' };
const root = new URL('..', import.meta.url);
const PRIVATE_FILE = new URL('.license/private-key.json', root);
const PUBLIC_TS = new URL('src/license/publicKey.ts', root);

const b64url = (bytes) => Buffer.from(bytes).toString('base64url');

/** Creates a license key. Exported for tests, so the extension's verifier is checked against this exact format. */
export async function issueKey(privateJwk, orderId, issuedAt = Date.now()) {
  if (typeof orderId !== 'string' || orderId.length === 0 || orderId.length > 64) {
    throw new Error('order id must be 1-64 characters');
  }
  const payload = b64url(new TextEncoder().encode(JSON.stringify({ v: 1, id: orderId, iat: issuedAt })));
  const key = await crypto.subtle.importKey('jwk', privateJwk, ALGORITHM, false, ['sign']);
  const sig = new Uint8Array(await crypto.subtle.sign(SIGN_PARAMS, key, new TextEncoder().encode(payload)));
  return `${KEY_PREFIX}${payload}.${b64url(sig)}`;
}

export async function generateKeyPair() {
  const pair = await crypto.subtle.generateKey(ALGORITHM, true, ['sign', 'verify']);
  const privateJwk = await crypto.subtle.exportKey('jwk', pair.privateKey);
  const { kty, crv, x, y } = await crypto.subtle.exportKey('jwk', pair.publicKey);
  return { privateJwk, publicJwk: { kty, crv, x, y } };
}

function publicKeyModule(jwk) {
  return `// Generated by \`npm run license -- keygen\`. The public half of the seller's signing key:
// safe to ship, it can only check keys, not create them.
export const LICENSE_PUBLIC_KEY: JsonWebKey = ${JSON.stringify(jwk, null, 2).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")};
`;
}

async function main([cmd, arg]) {
  if (cmd === 'keygen') {
    if (existsSync(PRIVATE_FILE)) {
      throw new Error('.license/private-key.json already exists. Refusing to overwrite: keys issued with it would stop working.');
    }
    const { privateJwk, publicJwk } = await generateKeyPair();
    mkdirSync(new URL('.license/', root), { recursive: true });
    writeFileSync(PRIVATE_FILE, JSON.stringify(privateJwk, null, 2) + '\n', { mode: 0o600 });
    writeFileSync(PUBLIC_TS, publicKeyModule(publicJwk));
    console.log('Created .license/private-key.json (keep secret, back it up) and src/license/publicKey.ts');
    return;
  }
  if (cmd === 'issue') {
    if (!existsSync(PRIVATE_FILE)) throw new Error('No private key. Run: npm run license -- keygen');
    console.log(await issueKey(JSON.parse(readFileSync(PRIVATE_FILE, 'utf8')), arg));
    return;
  }
  if (cmd === 'verify') {
    const src = readFileSync(PUBLIC_TS, 'utf8');
    const pub = { kty: 'EC', crv: 'P-256', x: /\bx: '([^']+)'/.exec(src)?.[1], y: /\by: '([^']+)'/.exec(src)?.[1] };
    const [payload, sig] = (arg ?? '').replace(/\s+/g, '').slice(KEY_PREFIX.length).split('.');
    const key = await crypto.subtle.importKey('jwk', pub, ALGORITHM, false, ['verify']);
    const ok =
      (arg ?? '').startsWith(KEY_PREFIX) &&
      (await crypto.subtle.verify(SIGN_PARAMS, key, Buffer.from(sig ?? '', 'base64url'), new TextEncoder().encode(payload ?? '')));
    console.log(ok ? `valid: ${Buffer.from(payload, 'base64url').toString()}` : 'INVALID');
    process.exitCode = ok ? 0 : 1;
    return;
  }
  console.log('Usage: npm run license -- keygen | issue <orderId> | verify <key>');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main(process.argv.slice(2)).catch((err) => {
    console.error(`license: ${err.message}`);
    process.exit(1);
  });
}
